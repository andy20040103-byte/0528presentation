let currentRole = null;

window.initRoleplay = function(role) {
  currentRole = role;
  document.getElementById('rp-start').classList.add('hidden');
  document.getElementById('rp-game').classList.remove('hidden');
  
  const history = document.getElementById('dialogue-history');
  history.innerHTML = '';
  document.getElementById('reset-rp-btn').classList.add('hidden');
  
  renderNode('start');
};

function renderNode(nodeId) {
  const node = dialogueData[currentRole].nodes[nodeId];
  const history = document.getElementById('dialogue-history');
  
  // Create chat bubble
  const bubble = document.createElement('div');
  bubble.className = `chat-bubble chat-${node.sender}`;
  // Convert newlines to br for rendering
  bubble.innerHTML = node.text.replace(/\n/g, '<br>');
  history.appendChild(bubble);
  history.scrollTop = history.scrollHeight;
  
  const choicesContainer = document.getElementById('choices-container');
  choicesContainer.innerHTML = '';
  
  if (node.choices.length > 0) {
    node.choices.forEach(choice => {
      const btn = document.createElement('button');
      btn.className = 'choice-btn';
      btn.textContent = choice.text;
      btn.onclick = () => {
        // Render player choice
        const playerBubble = document.createElement('div');
        playerBubble.className = 'chat-bubble chat-player';
        playerBubble.textContent = choice.text;
        history.appendChild(playerBubble);
        history.scrollTop = history.scrollHeight;
        
        // Disable buttons temporarily
        choicesContainer.innerHTML = '';
        
        // Small delay for next node
        setTimeout(() => {
          renderNode(choice.next);
        }, 500);
      };
      choicesContainer.appendChild(btn);
    });
  } else {
    // End of dialogue
    document.getElementById('reset-rp-btn').classList.remove('hidden');
  }
}

window.resetRoleplay = function() {
  document.getElementById('rp-game').classList.add('hidden');
  document.getElementById('rp-start').classList.remove('hidden');
};

// Modal Logic
document.addEventListener("DOMContentLoaded", () => {
  const triggers = document.querySelectorAll(".popup-trigger");
  const modal = document.getElementById("image-modal");
  const modalImg = document.getElementById("modal-image");

  triggers.forEach(trigger => {
    trigger.addEventListener("click", (e) => {
      e.preventDefault();
      const imgSrc = trigger.getAttribute("data-img");
      modalImg.src = imgSrc;
      modal.classList.remove("hidden");
    });
  });

  // Close when clicking outside image
  modal.addEventListener("click", (e) => {
    if (e.target === modal) {
      window.closeModal();
    }
  });
});

window.closeModal = function() {
  document.getElementById("image-modal").classList.add("hidden");
};

